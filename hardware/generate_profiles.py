"""Generate application feedback profiles; no Sony SDK types or protocols."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate():
    data = json.loads((ROOT / "production/dualsense_events.json").read_text())
    contract = json.loads((ROOT / "production/state_contract.json").read_text())
    events = data["events"]
    ids = [e["id"] for e in events]
    assert len(ids) == len(set(ids)), "Duplicate event"
    assert set(ids) == set(contract["events"]), "Event contract mismatch"
    rows = []
    for e in events:
        q = json.dumps
        rows.append("    {" + ", ".join([
            q(e["id"]), str(e["priority"]), str(e["ttl_ms"]),
            str(e["cooldown_ms"]), str(e["critical"]).lower(),
            str(e["presentation"]).lower(), q(e["trigger"]),
            str(e["left_trigger"]), str(e["right_trigger"]),
            q(e["wave"]), str(e["amplitude"]), str(e["pulse_hz"]),
            q(e["speaker"]), str(e["light"]),
        ]) + "},")
    return "// Generated by generate_profiles.py; edit JSON, then regenerate.\n" + \
        "#pragma once\n#include <array>\nnamespace lab04 {\n" + \
        f"inline const std::array<Profile, {len(rows)}> Profiles = {{{{\n" + \
        "\n".join(rows) + "\n}};\n}\n"


if __name__ == "__main__":
    import sys
    path = ROOT / "hardware/profiles.generated.hpp"
    content = generate()
    if "--check" in sys.argv:
        assert path.read_text() == content, "Generated profiles are stale"
        print("Profile/contract parity passed")
    else:
        path.write_text(content)
